def dedupe(recs: list[dict]) -> tuple[list[dict], dict]:
    seen_hash, seen_path = {}, {}
    kept, dup_hash, dup_path = [], 0, 0
    for r in recs:
        h = sha256(r["text"].encode())
        if h in seen_hash:
            dup_hash += 1
            r["_dup_of"] = seen_hash[h]
            continue
        p = r["path"]
        n = 1
        while p in seen_path:
            n += 1
            root, ext = os.path.splitext(r["path"])
            p = f"{root}-{n}{ext}"
            dup_path += 1
        seen_hash[h] = r["path"]
        seen_path[p] = True
        r["path"] = p
        r["sha256"] = h
        kept.append(r)
    return kept, {"duplicate_content": dup_hash, "renamed_collisions": dup_path}


def write_corpus(recs: list[dict]) -> None:
    for r in recs:
        dst = os.path.join(HERE, r["path"])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(r["text"])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--source", default="all")
    args = ap.parse_args()
    s = args.scale

    recs: list[dict] = []
    if args.source in ("all", "gutenberg"):
        sys.stderr.write("gutenberg: discovering top scores...\n")
        recs += harvest_gutenberg(int(120 * s), cap_bytes=int(2e6))
    if args.source in ("all", "wikipedia"):
        sys.stderr.write("wikipedia: walking categories...\n")
        recs += harvest_mediawiki("en.wikipedia.org", "wikipedia-en", WIKI_SEEDS,
                                 per_cat=300, depth=2, cap=int(3000 * s), min_words=120)
    if args.source in ("all", "wikisource"):
        sys.stderr.write("wikisource: walking categories...\n")
        recs += harvest_mediawiki("en.wikisource.org", "wikisource-en", WS_SEEDS,
                                 per_cat=200, depth=2, cap=int(400 * s), min_words=120,
                                 intro=False)

    recs, dd = dedupe(recs)
    write_corpus(recs)

    for r in recs:
        b = len(r["text"].encode())
        r["bytes"] = b
        r["words"] = wc(r["text"])
        r.pop("text", None)

    total_words = sum(r["words"] for r in recs)
    total_bytes = sum(r["bytes"] for r in recs)
    manifest = {
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seed": SEED,
        "harvester": "harvest_corpus.py",
        "scale": args.scale,
        "sources": SOURCES,
        "totals": {"files": len(recs), "words": total_words, "bytes": total_bytes},
        "removed": dd,
        "files": sorted(recs, key=lambda r: r["path"]),
    }
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)

    # checksums for verification
    with open(os.path.join(HERE, "SHA256SUMS"), "w", encoding="utf-8") as f:
        for r in manifest["files"]:
            f.write(f"{r['sha256']}  {r['path']}\n")

    sys.stderr.write(f"\nfiles={len(recs)} words={total_words} bytes={total_bytes} "
                     f"dup_content={dd['duplicate_content']}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
