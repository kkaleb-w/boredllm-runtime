#!/usr/bin/env python3
"""Frozen-corpus harvester for the BoredLLM runtime.

HARD REQUIREMENT: every byte of text here is real human-authored prose that was
written before any language model existed. Nothing is generated by an AI, and
nothing is paraphrased, summarised, or recomposed by one. The harvester only
downloads, unwraps licensing/boilerplate, and normalises whitespace.

Sources (all keyless, all bulk-friendly, all checked against robots.txt):
  * Project Gutenberg  - public-domain literature. Served from /cache/epub and
    /files; robots.txt only disallows /ebooks/search, which we never touch.
  * Wikipedia (en)     - encyclopedic prose via the MediaWiki action API.
    Text is CC BY-SA 4.0; attribution recorded per file.
  * Wikisource (en)    - public-domain / CC BY-SA primary texts via the same API.

Deliberately NOT used: Standard Ebooks (robots.txt disallows
/ebooks/*/downloads/*), and any source that forbids automated collection.

Usage:
    python3 harvest_corpus.py                 # full build into ./text + ./manifest.json
    python3 harvest_corpus.py --source gutenberg
    python3 harvest_corpus.py --scale 0.1     # small smoke build

The build is idempotent: re-running overwrites the same paths, and per-document
content hashes let us drop exact duplicates. No network calls are made twice for
the same URL within a single run (simple in-process cache).
"""
